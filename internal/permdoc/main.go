// Command permdoc writes the generated part of docs/reference/permissions.md: the permission table
// and the table of built-in roles, from the catalogue and the roles of internal/authz and from the
// operations of the administration API (sprint 4.3). The part sits between two markers; text
// outside them is written by hand.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"os"
	"slices"
	"sort"
	"strings"

	"github.com/pandokos/pandokos/internal/adminapi"
	"github.com/pandokos/pandokos/internal/authz"
)

const (
	beginMarker = "<!-- generated by internal/permdoc: begin -->"
	endMarker   = "<!-- generated by internal/permdoc: end -->"
)

// Generate returns the generated part of the page, without the markers: the permission table (with
// the operations that need each permission and the built-in roles that hold it), the table of
// built-in roles, the matrix of permissions by role for the tenant and for the platform, and the
// operations that require a reason. The order is fixed: the catalogue's, the order of roles, the
// operations by ID, whatever the order of the arguments.
func Generate(perms []authz.Permission, roles []authz.Role, ops []adminapi.Operation) []byte {
	byPerm := map[string][]string{}
	var reasons []string
	for _, op := range ops {
		if op.Permission != "" {
			byPerm[op.Permission] = append(byPerm[op.Permission], op.ID)
		}
		if op.ReasonRequired {
			reasons = append(reasons, op.ID)
		}
	}
	for _, ids := range byPerm {
		sort.Strings(ids)
	}
	sort.Strings(reasons)
	holds := func(r authz.Role, name string) bool { return slices.Contains(r.Permissions, name) }

	var b bytes.Buffer
	b.WriteString("## Permissions\n\n")
	b.WriteString("| Permission | Scope | Attributes | Allows | Operations | Held by |\n|---|---|---|---|---|---|\n")
	for _, p := range perms {
		var attrs []string
		if p.InTenant {
			attrs = append(attrs, "in tenant")
		}
		if p.Support {
			attrs = append(attrs, "support")
		}
		var holders []string
		for _, r := range roles {
			if holds(r, p.Name) {
				holders = append(holders, r.Name)
			}
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s |\n", p.Name, p.Scope, orDash(strings.Join(attrs, ", ")), cell(p.Description),
			orDash(quoted(byPerm[p.Name])), orDash(quoted(holders)))
	}

	b.WriteString("\n## Built-in roles\n\n")
	b.WriteString("| Role | Scope | Members | Description | Permissions |\n|---|---|---|---|---|\n")
	for _, r := range roles {
		members := "no"
		if r.Members {
			members = "yes"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", r.Name, r.Scope, members, cell(r.Description), quoted(r.Permissions))
	}

	for _, scope := range []authz.Scope{authz.ScopeTenant, authz.ScopePlatform} {
		var cols []authz.Role
		for _, r := range roles {
			if r.Scope == scope {
				cols = append(cols, r)
			}
		}
		fmt.Fprintf(&b, "\n## Permissions by %s role\n\n| %s permission |", scope, strings.ToUpper(string(scope)[:1])+string(scope)[1:])
		for _, r := range cols {
			fmt.Fprintf(&b, " `%s` |", r.Name)
		}
		b.WriteString(" Allows |\n|---|")
		for range cols {
			b.WriteString("---|")
		}
		b.WriteString("---|\n")
		for _, p := range perms {
			if p.Scope != scope {
				continue
			}
			fmt.Fprintf(&b, "| `%s` |", p.Name)
			for _, r := range cols {
				mark := "-"
				if holds(r, p.Name) {
					mark = "x"
				}
				fmt.Fprintf(&b, " %s |", mark)
			}
			fmt.Fprintf(&b, " %s |\n", cell(p.Description))
		}
	}

	b.WriteString("\n## Operations that require a reason\n\n")
	b.WriteString("The request body must carry a `reason` that is not empty after trimming; it is recorded in the audit log.\n\n")
	for _, id := range reasons {
		fmt.Fprintf(&b, "- `%s`\n", id)
	}
	return b.Bytes()
}

// quoted writes names as code, separated by commas.
func quoted(names []string) string {
	out := make([]string, len(names))
	for i, n := range names {
		out[i] = "`" + n + "`"
	}
	return strings.Join(out, ", ")
}

func orDash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

// cell makes text safe inside a table cell.
func cell(s string) string { return strings.ReplaceAll(strings.ReplaceAll(s, "|", `\|`), "\n", " ") }

// replace returns doc with what lies between the markers replaced by body; a nil body leaves doc as it is.
func replace(doc, body []byte) ([]byte, error) {
	if body == nil {
		return doc, nil
	}
	begin := bytes.Index(doc, []byte(beginMarker))
	end := bytes.Index(doc, []byte(endMarker))
	if begin < 0 || end < begin || bytes.Count(doc, []byte(beginMarker)) != 1 || bytes.Count(doc, []byte(endMarker)) != 1 {
		return nil, errors.New("the page needs one begin marker followed by one end marker")
	}
	var out bytes.Buffer
	out.Write(doc[:begin+len(beginMarker)])
	out.WriteByte('\n')
	out.Write(body)
	if !bytes.HasSuffix(body, []byte("\n")) {
		out.WriteByte('\n')
	}
	out.Write(doc[end:])
	return out.Bytes(), nil
}

func run(path string) error {
	doc, err := os.ReadFile(path) //nolint:gosec // the page named by the -out flag of a build tool
	if err != nil {
		return err
	}
	out, err := replace(doc, Generate(authz.Catalogue(), authz.Roles(), adminapi.Operations))
	if err != nil {
		return err
	}
	if bytes.Equal(out, doc) {
		return nil
	}
	return os.WriteFile(path, out, 0o644) //nolint:gosec // a documentation page, readable by everybody
}

func main() {
	out := flag.String("out", "", "the page to update")
	flag.Parse()
	if *out == "" {
		fmt.Fprintln(os.Stderr, "permdoc: -out is required")
		os.Exit(2)
	}
	if err := run(*out); err != nil {
		fmt.Fprintln(os.Stderr, "permdoc:", err)
		os.Exit(1)
	}
}
