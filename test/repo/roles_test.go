const (
	permBegin = "<!-- generated by internal/permdoc: begin -->"
	permEnd   = "<!-- generated by internal/permdoc: end -->"
)

// TestPermissionReferenceIsGenerated is T-R59: docs/reference/permissions.md between its markers is
// what internal/permdoc writes, the Makefile generates and checks it, and nothing outside the
// markers is a role or permission table of its own that could contradict it.
func TestPermissionReferenceIsGenerated(t *testing.T) {
	doc := read(t, "docs/reference/permissions.md")
	if strings.Count(doc, permBegin) != 1 || strings.Count(doc, permEnd) != 1 || strings.Index(doc, permBegin) > strings.Index(doc, permEnd) {
		t.Fatalf("permissions.md needs one begin marker followed by one end marker")
	}
	inside := doc[strings.Index(doc, permBegin)+len(permBegin) : strings.Index(doc, permEnd)]
	outside := doc[:strings.Index(doc, permBegin)] + doc[strings.Index(doc, permEnd)+len(permEnd):]

	t.Run("the section is what the generator writes", func(t *testing.T) {
		tmp := filepath.Join(t.TempDir(), "permissions.md")
		if err := os.WriteFile(tmp, []byte(doc), 0o600); err != nil {
			t.Fatal(err)
		}
		cmd := exec.Command("go", "run", "./internal/permdoc", "-out", tmp)
		cmd.Dir = root(t)
		var stderr bytes.Buffer
		cmd.Stderr = &stderr
		if err := cmd.Run(); err != nil {
			t.Fatalf("go run ./internal/permdoc: %v\n%s", err, stderr.String())
		}
		got, err := os.ReadFile(tmp)
		if err != nil {
			t.Fatal(err)
		}
		if string(got) != doc {
			t.Error("docs/reference/permissions.md is not what internal/permdoc writes: run make generate and commit the result")
		}
		// The generator wrote something: every permission and every role is in the section.
		for _, p := range authz.Catalogue() {
			if !strings.Contains(inside, "`"+p.Name+"`") {
				t.Errorf("the generated section does not name the permission %s", p.Name)
			}
		}
		for _, r := range authz.Roles() {
			if !strings.Contains(inside, "`"+r.Name+"`") {
				t.Errorf("the generated section does not name the role %s", r.Name)
			}
		}
	})
	t.Run("the Makefile generates and checks the page", func(t *testing.T) {
		mk := read(t, "Makefile")
		if m := regexp.MustCompile(`(?m)^GENERATED :=(.*)$`).FindStringSubmatch(mk); m == nil || !strings.Contains(m[1], "docs/reference/permissions.md") {
			t.Error("GENERATED of the Makefile does not name docs/reference/permissions.md")
		}
		if !regexp.MustCompile(`(?m)^\s+go run \./internal/permdoc -out docs/reference/permissions\.md\s*$`).MatchString(mk) {
			t.Error("the generate target of the Makefile does not run internal/permdoc on docs/reference/permissions.md")
		}
	})
	t.Run("nothing outside the markers is a table of roles or permissions", func(t *testing.T) {
		names := map[string]bool{}
		for _, p := range authz.Catalogue() {
			names[p.Name] = true
		}
		for _, r := range authz.Roles() {
			names[r.Name] = true
		}
		for _, line := range strings.Split(outside, "\n") {
			if !strings.HasPrefix(strings.TrimSpace(line), "|") {
				continue
			}
			first := strings.Trim(strings.TrimSpace(strings.SplitN(strings.TrimPrefix(strings.TrimSpace(line), "|"), "|", 2)[0]), "` ")
			if names[first] {
				t.Errorf("a table outside the generated section has a row for %q: %s", first, line)
			}
		}
		for _, stale := range []string{"Custom roles are not yet possible", "not yet possible (sprint 4.3)", "no platform role is a usage viewer and the only holders"} {
			if strings.Contains(outside, stale) {
				t.Errorf("the prose outside the generated section still says %q", stale)
			}
		}
		// The prose that stays is the prose the other tests read.
		for _, w := range []string{"default is deny", "tenant_suspended", "not_found"} {
			if !strings.Contains(outside, w) {
				t.Errorf("the page no longer explains %q outside the generated section", w)
			}
		}
	})
}

// TestBuiltinNamesInMigration is T-R60: the names that migration 0014 refuses for a custom role
// are exactly the names of the built-in roles, and the two prefixes are there.
func TestBuiltinNamesInMigration(t *testing.T) {
	sql := read(t, "internal/store/migrations/sql/0014_roles_support.sql")
	m := regexp.MustCompile(`(?s)tenant_role_name_not_builtin CHECK \(\s*name NOT IN \((.*?)\)`).FindStringSubmatch(sql)
	if m == nil {
		t.Fatal("migration 0014 has no constraint tenant_role_name_not_builtin of the form name NOT IN (...)")
	}
	var got []string
	for _, n := range regexp.MustCompile(`'([^']+)'`).FindAllStringSubmatch(m[1], -1) {
		got = append(got, n[1])
	}
	var want []string
	for _, r := range authz.Roles() {
		want = append(want, r.Name)
	}
	sort.Strings(got)
	sort.Strings(want)
	if strings.Join(got, ",") != strings.Join(want, ",") {
		t.Errorf("the migration refuses %v, authz.Roles() has %v", got, want)
	}
	if !strings.Contains(sql, `name !~ '^(platform|pandokos)-'`) {
		t.Error("the migration does not refuse the prefixes platform- and pandokos-")
	}
}

// roleConstants returns the names of the constants of internal/authz that name a built-in role.
func roleConstants(t *testing.T) map[string]string {
	t.Helper()
	f, err := parser.ParseFile(token.NewFileSet(), filepath.Join(root(t), "internal/authz/roles.go"), nil, 0)
	if err != nil {
		t.Fatal(err)
	}
	out := map[string]string{}
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok || g.Tok != token.CONST {
			continue
		}
		for _, sp := range g.Specs {
			vs := sp.(*ast.ValueSpec)
			for i, n := range vs.Names {
				if strings.HasPrefix(n.Name, "Role") && i < len(vs.Values) {
					if lit, ok := vs.Values[i].(*ast.BasicLit); ok {
						out[n.Name] = strings.Trim(lit.Value, `"`)
					}
				}
			}
		}
	}
	if len(out) < 10 {
		t.Fatalf("%d role constants found in internal/authz/roles.go, want the ten", len(out))
	}
	return out
}

// TestNoDecisionByRoleName is T-R61: outside internal/authz a role constant is named only where an
// identity is born with a fixed role, and nothing compares a role name to decide.
func TestNoDecisionByRoleName(t *testing.T) {
	consts := roleConstants(t)
	byName := map[string]bool{}
	for _, v := range consts {
		byName[v] = true
	}
	// The places of section 5.11.
	allowed := map[string]map[string]bool{
		"internal/admin/tenants.go":       {"RoleOwner": true},
		"internal/admin/bootstrap.go":     {"RolePlatformAdmin": true},
		"internal/account/host.go":        {"RolePlatformAdmin": true},
		"internal/admin/platform_keys.go": {"RolePlatformAdmin": true},
	}
	fset := token.NewFileSet()
	seen := 0
	for _, file := range goFiles(t, "internal", "cmd") {
		rel, _ := filepath.Rel(root(t), file)
		rel = filepath.ToSlash(rel)
		if strings.HasPrefix(rel, "internal/authz/") || strings.HasPrefix(rel, "internal/adminapi/") || strings.HasPrefix(rel, "internal/store/queries/") {
			continue
		}
		f, err := parser.ParseFile(fset, file, nil, 0)
		if err != nil {
			t.Fatal(err)
		}
		seen++
		isRoleOperand := func(e ast.Expr) bool {
			var text string
			switch x := e.(type) {
			case *ast.Ident:
				text = x.Name
			case *ast.SelectorExpr:
				text = x.Sel.Name
			case *ast.IndexExpr:
				if s, ok := x.X.(*ast.SelectorExpr); ok {
					text = s.Sel.Name
				}
			}
			return strings.Contains(strings.ToLower(text), "role")
		}
		isRoleName := func(e ast.Expr) bool {
			switch x := e.(type) {
			case *ast.BasicLit:
				return x.Kind == token.STRING && byName[strings.Trim(x.Value, `"`)]
			case *ast.SelectorExpr:
				id, ok := x.X.(*ast.Ident)
				return ok && id.Name == "authz" && consts[x.Sel.Name] != ""
			}
			return false
		}
		ast.Inspect(f, func(n ast.Node) bool {
			switch x := n.(type) {
			case *ast.SelectorExpr:
				if id, ok := x.X.(*ast.Ident); ok && id.Name == "authz" && consts[x.Sel.Name] != "" && !allowed[rel][x.Sel.Name] {
					t.Errorf("%s: authz.%s is named outside the places of section 5.11", fset.Position(x.Pos()), x.Sel.Name)
				}
			case *ast.BinaryExpr:
				if (x.Op == token.EQL || x.Op == token.NEQ) && ((isRoleName(x.X) && isRoleOperand(x.Y)) || (isRoleName(x.Y) && isRoleOperand(x.X))) {
					t.Errorf("%s: a role is compared with a name; decide by permissions", fset.Position(x.Pos()))
				}
			case *ast.CaseClause:
				for _, e := range x.List {
					if lit, ok := e.(*ast.BasicLit); ok && lit.Kind == token.STRING && byName[strings.Trim(lit.Value, `"`)] {
						t.Errorf("%s: a case on the role name %s", fset.Position(lit.Pos()), lit.Value)
					}
				}
			case *ast.CallExpr:
				// slices.Contains(p.Roles, "tenant-admin") and the like.
				if sel, ok := x.Fun.(*ast.SelectorExpr); ok && (sel.Sel.Name == "Contains" || sel.Sel.Name == "Index") && len(x.Args) == 2 && isRoleOperand(x.Args[0]) && isRoleName(x.Args[1]) {
					t.Errorf("%s: a role list is searched for a name; decide by permissions", fset.Position(x.Pos()))
				}
			}
			return true
		})
	}
	if seen < 100 {
		t.Fatalf("%d files read", seen)
	}
	// The one legitimate use of a role in the configuration is whether a person can hold it.
	if !strings.Contains(read(t, "internal/authz/roles.go"), "Members") {
		t.Error("authz.Role has no Members: whether a person can hold a role is a property of the role")
	}
}

// TestPlatformReadsNoTenantUsage is T-R62, the repository test of 5.4 extended: no handler of an
// operation whose permission is of scope platform, and no handler of an operation that a support
// action can reach (a permission with the attribute Support), calls a statement on a tenant's
// usage records, limit events or price lists (usage.sql, limits.sql, tenant_prices.sql).
func TestPlatformReadsNoTenantUsage(t *testing.T) {
	stmts := usageStatements(t)
	fset := token.NewFileSet()
	body := map[string]*ast.FuncDecl{}
	for _, file := range goFiles(t, "internal/admin") {
		f, err := parser.ParseFile(fset, file, nil, 0)
		if err != nil {
			t.Fatal(err)
		}
		for _, d := range f.Decls {
			if fn, ok := d.(*ast.FuncDecl); ok && fn.Body != nil {
				body[fn.Name.Name] = fn
			}
		}
	}
	reaches := func(start string) bool {
		seen := map[string]bool{}
		var walk func(name string) bool
		walk = func(name string) bool {
			fn := body[name]
			if fn == nil || seen[name] {
				return false
			}
			seen[name] = true
			found := false
			ast.Inspect(fn.Body, func(n ast.Node) bool {
				call, ok := n.(*ast.CallExpr)
				if !ok || found {
					return !found
				}
				callee := ""
				switch c := call.Fun.(type) {
				case *ast.SelectorExpr:
					callee = c.Sel.Name
				case *ast.Ident:
					callee = c.Name
				}
				if stmts[callee] || (callee != name && walk(callee)) {
					found = true
				}
				return !found
			})
			return found
		}
		return walk(start)
	}
	platform, support := 0, 0
	for _, op := range adminapi.Operations {
		perm, ok := authz.Lookup(op.Permission)
		if !ok || (perm.Scope != authz.ScopePlatform && !perm.Support) {
			continue
		}
		handler := strings.ToUpper(op.ID[:1]) + op.ID[1:]
		if body[handler] == nil {
			t.Errorf("no handler %s for %s", handler, op.ID)
			continue
		}
		if perm.Scope == authz.ScopePlatform {
			platform++
		} else {
			support++
		}
		if reaches(handler) {
			t.Errorf("%s (permission %s) reaches a statement on a tenant's usage, limit events or prices", handler, op.Permission)
		}
	}
	if platform < 45 || support < 20 {
		t.Errorf("%d platform handlers and %d handlers under a Support permission were checked: the test proves nothing", platform, support)
	}
	// The hook that gives a platform principal a tenant is not a handler, and no statement of the
	// support action's own files names a usage table either.
	for _, sql := range []string{"roles.sql", "support.sql"} {
		text := read(t, "internal/store/queries/sql/"+sql)
		for _, tbl := range usageTables {
			if strings.Contains(text, tbl) {
				t.Errorf("%s names %s", sql, tbl)
			}
		}
	}
}

// TestRolesGuide is T-R63: the guide of roles and support actions names what an operator needs, and
// the two decision records exist and are indexed.
func TestRolesGuide(t *testing.T) {
	doc := read(t, "docs/operations/roles.md")
	lower := strings.ToLower(doc)
	var missing []string
	need := func(words ...string) {
		for _, w := range words {
			if !strings.Contains(doc, w) {
				missing = append(missing, w)
			}
		}
	}
	for _, r := range authz.Roles() {
		need("`" + r.Name + "`")
	}
	need("support.enabled", "support.max_duration", "escalation_refused", "support_disabled", "role_in_use")
	for _, id := range []string{"suspendTenant", "reactivateTenant", "disableTenantCredential", "revokeTenantCredential", "openSupportAction",
		"resetUserPassword", "resetMemberPassword", "deactivateRole", "activateRole"} {
		need("`" + id + "`")
	}
	if len(missing) > 0 {
		t.Errorf("docs/operations/roles.md lacks %v", missing)
	}
	// The recovery of a tenant that lost its administrators (section 5.7).
	for _, w := range []string{"recover", "tenant-support open", "tenant-support close", "service_account:read", "virtual_key:write", "member:write", "key create"} {
		if !strings.Contains(lower, strings.ToLower(w)) {
			t.Errorf("the recovery steps of docs/operations/roles.md lack %q", w)
		}
	}
	for _, k := range config.Keys() {
		if (k.Name == "support.enabled" || k.Name == "support.max_duration") && !strings.Contains(read(t, "docs/operations/configuration.md"), "`"+k.Name+"`") {
			t.Errorf("configuration.md does not name %s", k.Name)
		}
	}
	index := read(t, "docs/adr/README.md")
	for _, prefix := range []string{"0060", "0061"} {
		files, _ := filepath.Glob(filepath.Join(root(t), "docs/adr", prefix+"-*.md"))
		if len(files) != 1 {
			t.Errorf("docs/adr has %d files for ADR %s, want one", len(files), prefix)
			continue
		}
		name := filepath.Base(files[0])
		if !strings.Contains(index, "("+name+")") {
			t.Errorf("docs/adr/README.md does not index %s", name)
		}
		if !regexp.MustCompile(`(?m)^- Status: accepted\s*$`).MatchString(read(t, "docs/adr/"+name)) {
			t.Errorf("%s is not accepted", name)
		}
	}
}
